"""Build formal/build/argmin_miter.sv from the RTL's own tree text.

Ruling TF4. The tree five-way select in `src/pe_engine.v` is proved equal to
the serial loop it replaced. ⛔ THE PROOF MUST RUN ON THE SHIPPED TEXT, not a
copy of it: this script lifts the lines between `---- BEGIN ARGMIN TREE ----`
and `---- END ARGMIN TREE ----` verbatim into the miter, so an edit to the
RTL's tree is an edit to what is proved. A missing or duplicated marker is a
failure, not a skip.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RTL = os.path.join(ROOT, "src", "pe_engine.v")
OUT = os.path.join(HERE, "build", "argmin_miter.sv")
BEGIN, END = "---- BEGIN ARGMIN TREE ----", "---- END ARGMIN TREE ----"

HEAD = """// GENERATED by formal/make_argmin_miter.py from src/pe_engine.v -- do not edit
module argmin_miter (
  input  wire [4:0]  ready,
  input  wire [15:0] k0, k1, k2, k3, k4
);
  localparam integer LW = 3, TS_W = 16;
  wire [TS_W-1:0] edf_key_off [0:4];
  assign edf_key_off[0] = k0;
  assign edf_key_off[1] = k1;
  assign edf_key_off[2] = k2;
  assign edf_key_off[3] = k3;
  assign edf_key_off[4] = k4;

  // ---- the SERIAL reference: the loop the tree replaced, verbatim ----
  reg [LW-1:0]   s_winner;
  reg            s_winner_v;
  reg [TS_W-1:0] best;
  integer        k;
  always @* begin
    s_winner   = {LW{1'b0}};
    s_winner_v = 1'b0;
    best  = {TS_W{1'b1}};
    for (k = 0; k < 5; k = k + 1) begin
      if (ready[k] && (!s_winner_v || edf_key_off[k] < best)) begin
        s_winner   = k[LW-1:0];
        s_winner_v = 1'b1;
        best  = edf_key_off[k];
      end
    end
  end

  // ---- the TREE, lifted from src/pe_engine.v ----
  reg [LW-1:0]   winner;
  reg            winner_v;
"""

TAIL = """
  // ---- the claim: identical outputs for every input ----
  always @* begin
    assert (winner_v == s_winner_v);
    assert (winner == s_winner);
  end
endmodule
"""


def main() -> int:
    lines = open(RTL, encoding="utf-8").read().splitlines()
    b = [i for i, l in enumerate(lines) if BEGIN in l]
    e = [i for i, l in enumerate(lines) if END in l]
    if len(b) != 1 or len(e) != 1 or not b[0] < e[0]:
        print("*** FAIL argmin markers: %d BEGIN, %d END in src/pe_engine.v"
              % (len(b), len(e)))
        return 1
    body = lines[b[0] + 1:e[0]]
    out = OUT
    # ⛔ THE MUST-FIRE: a tree whose first node breaks the tie rule (`<=` lets
    # the higher index win on equal keys) must FAIL the same proof. A proof
    # that passes on a broken tree proves nothing about the real one.
    if "--mutate" in sys.argv:
        needle = "edf_key_off[1] < edf_key_off[0]"
        hits = [i for i, l in enumerate(body) if needle in l]
        if len(hits) != 1:
            print("*** FAIL must-fire: %r found %d times" % (needle, len(hits)))
            return 1
        body[hits[0]] = body[hits[0]].replace(needle,
                                              "edf_key_off[1] <= edf_key_off[0]")
        out = OUT.replace(".sv", "_mut.sv")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEAD + "\n".join(body) + "\n" + TAIL)
    print("argmin miter: %d tree lines lifted from src/pe_engine.v:%d-%d"
          % (len(body), b[0] + 2, e[0]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
