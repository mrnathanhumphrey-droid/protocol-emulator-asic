"""Build formal/build/preselect_miter.sv from the RTL's own pre-select text.

Ruling C2 (after TF2-R). `argmin_equiv.sby` proves the one-hot `winner_oh`
names exactly the binary winner. This proves the step after it: the flat
AND-OR pick over per-lane heads equals the indexed mux it replaced,

    w_act   == winner_v ? l_act [hix[winner]] : 0
    w_hv    == winner_v & l_actv[hix[winner]]
    w_armed == winner_v & l_armed[winner]

for EVERY slot contents, select bits and armed bits, under the one premise
the argmin proof discharges: `winner_oh == (winner_v ? 1 << winner : 0)`.
Together the two proofs cover the dispatch select end to end.

⛔ THE PROOF MUST RUN ON THE SHIPPED TEXT. The `hix` assign, the `g_head`
generate and the AND-OR `always` block are lifted VERBATIM from
`src/pe_engine.v` by landmark lines (not markers: adding markers would be an
RTL edit, and lock hygiene makes any RTL edit cost a full harden). Each
landmark must match exactly once; a missing or duplicated landmark is a
failure, not a skip.
MUST-FIRE (`--mutate`): `w_act` drops its one-hot gate on every lane, so it
ORs all five heads. The proof must FAIL on it.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RTL = os.path.join(ROOT, "src", "pe_engine.v")
OUT = os.path.join(HERE, "build", "preselect_miter.sv")

HIX = "      assign hix[gs] = gs * SPL + (((SPL > 1) &&  l_sel[gs]) ? 1 : 0);"
HEAD_FIRST = "  wire [ACT_W-1:0] hw [0:N_LANES-1];"
BLOCK_LAST = "      w_armed = w_armed | (winner_oh[wk] & l_armed[wk]);"
MUT_FROM = "w_act   = w_act   | ({ACT_W{winner_oh[wk]}} & hw[wk]);"
MUT_TO = "w_act   = w_act   | hw[wk];"

HEAD = """// GENERATED by formal/make_preselect_miter.py from src/pe_engine.v -- do not edit
module preselect_miter (
  input  wire [2:0]  winner,
  input  wire        winner_v,
  input  wire [4:0]  winner_oh,
  input  wire [4:0]  l_sel,
  input  wire [4:0]  l_armed,
  input  wire [9:0]  l_actv,
  input  wire [23:0] a0, a1, a2, a3, a4, a5, a6, a7, a8, a9
);
  // ACT_W is a free width here: every operation lifted is bitwise.
  localparam integer N_LANES = 5, SPL = 2, SIW = 4, ACT_W = 24;
  wire [ACT_W-1:0] l_act [0:9];
  assign l_act[0] = a0; assign l_act[1] = a1; assign l_act[2] = a2;
  assign l_act[3] = a3; assign l_act[4] = a4; assign l_act[5] = a5;
  assign l_act[6] = a6; assign l_act[7] = a7; assign l_act[8] = a8;
  assign l_act[9] = a9;

  // ---- the premise argmin_equiv.sby proves ----
  always @* begin
    assume (winner_v ? (winner < 5) : (winner == 3'd0));
    assume (winner_oh == (winner_v ? (5'b00001 << winner) : 5'b00000));
  end

  // ---- lifted from src/pe_engine.v ----
  genvar gs, gi;
  wire [SIW-1:0] hix [0:N_LANES-1];
  generate
    for (gs = 0; gs < N_LANES; gs = gs + 1) begin : g_slot
"""

TAIL = """
  // ---- the claim: the AND-OR pick == the indexed mux it replaced ----
  always @* begin
    assert (w_act   == (winner_v ? l_act[hix[winner]] : {ACT_W{1'b0}}));
    assert (w_hv    == (winner_v & l_actv[hix[winner]]));
    assert (w_armed == (winner_v & l_armed[winner]));
  end
endmodule
"""


def find_once(lines, needle):
    hits = [i for i, l in enumerate(lines) if l == needle]
    return hits[0] if len(hits) == 1 else None, len(hits)


def main() -> int:
    lines = open(RTL, encoding="utf-8").read().splitlines()
    got = {}
    for name, needle in (("hix", HIX), ("head", HEAD_FIRST),
                         ("last", BLOCK_LAST)):
        i, n = find_once(lines, needle)
        if i is None:
            print("*** FAIL preselect landmark %r: found %d times in "
                  "src/pe_engine.v" % (name, n))
            return 1
        got[name] = i
    # the always block closes with the loop's `end` and the block's `end`
    a, z = got["head"], got["last"] + 2
    if not a < z or [l.strip() for l in lines[z - 1:z + 1]] != ["end", "end"]:
        print("*** FAIL preselect block does not close where expected "
              "(src/pe_engine.v:%d)" % (z + 1))
        return 1
    body = lines[a:z + 1]
    out = OUT
    if "--mutate" in sys.argv:
        hits = [i for i, l in enumerate(body) if MUT_FROM in l]
        if len(hits) != 1:
            print("*** FAIL must-fire: %r found %d times" % (MUT_FROM, len(hits)))
            return 1
        body[hits[0]] = body[hits[0]].replace(MUT_FROM, MUT_TO)
        out = OUT.replace(".sv", "_mut.sv")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEAD + lines[got["hix"]] + "\n    end\n  endgenerate\n"
                 + "\n".join(body) + "\n" + TAIL)
    print("preselect miter: hix from src/pe_engine.v:%d, pre-select "
          "src/pe_engine.v:%d-%d" % (got["hix"] + 1, a + 1, z + 1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
