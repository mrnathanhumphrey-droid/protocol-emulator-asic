#!/usr/bin/env python3
"""GATE progress-bounds -- progress.vh's liveness bound is GENERATED, per action.

    python test/gen_progress_bounds.py           check (the gate; token below)
    python test/gen_progress_bounds.py --write   regenerate test/progress_bounds.vh

⛔⛔ WHY (Wilson 11-14, coverage step 2). Layer A of `test/progress.vh` fired on
any action re-dispatched more than a TYPED 64 times, under a typed comment
("the longest is a 17-dispatch 8-bit clocked receive"). The USB buffer send
(bundle 5) holds ONE action for a whole packet, up to 112 wire bits, so five
coverage arms read a false hang -- and the premise had gone stale with nothing
to say so. A global maximum would also miss a stuck SHORT action: a self-timed
SHIFTIN held 8 bits too long stays far under 64.
⇒ The bound is now the CURRENT action's own maximum, from
  `pe_isa.dispatch_max` (the one source, also the admissibility gate's), emitted
  here as lookup tables progress.vh indexes by the action's 4-bit count. This
  gate holds the tracked header to a fresh generation.
MUST-FIRES: a perturbed table entry, and a missing kind, each red.
POSITIVE TOKEN: `GATE progress-bounds: PASSED`.
"""
from __future__ import annotations

import io
import os
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import pe_isa as I  # noqa: E402

OUT = os.path.join(HERE, "progress_bounds.vh")
#: the table kinds indexed by count (usb_send / other are scalars)
TABLES = ("ck_shift", "ck_shiftin", "st_shift", "st_shiftin", "usb_rx")


def render():
    """The header text, from pe_isa.dispatch_max."""
    n = 1 << I.CNT_W
    lines = [
        "// GENERATED by test/gen_progress_bounds.py from test/pe_isa.py dispatch_max",
        "// -- DO NOT EDIT. progress.vh's per-action liveness bound (Wilson 11-14):",
        "// the most dispatches an action of each kind takes before it retires,",
        "// indexed by the action's 4-bit count. Regenerate with --write.",
        "localparam integer PG_USB_SEND_MAX = %d;" % I.dispatch_max("usb_send"),
        "localparam integer PG_OTHER_MAX = %d;" % I.dispatch_max("other"),
    ]
    for kind in TABLES:
        lines.append("function integer pg_max_%s(input [%d:0] c);" % (kind, I.CNT_W - 1))
        lines.append("  case (c)")
        for c in range(n):
            lines.append("    %d: pg_max_%s = %d;" % (c, kind, I.dispatch_max(kind, c)))
        lines.append("    default: pg_max_%s = 0;" % kind)
        lines.append("  endcase")
        lines.append("endfunction")
    return "\n".join(lines) + "\n"


def problems(tracked, fresh):
    """[problem] comparing the tracked header with a fresh generation."""
    if tracked is None:
        return ["test/progress_bounds.vh is missing -- run --write"]
    if tracked.replace("\r\n", "\n") != fresh:
        t = tracked.replace("\r\n", "\n").splitlines()
        f = fresh.splitlines()
        first = next((i for i, (a, b) in enumerate(zip(t, f)) if a != b), min(len(t), len(f)))
        return ["test/progress_bounds.vh is STALE against pe_isa.dispatch_max (first "
                "difference at line %d) -- run --write" % (first + 1)]
    return []


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    fresh = render()
    if "--write" in argv:
        with io.open(OUT, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(fresh)
        print("wrote %s" % os.path.relpath(OUT, ROOT))
        return 0
    print("GATE progress-bounds -- progress.vh's per-action liveness bound is generated")
    tracked = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else None
    probs = problems(tracked, fresh)
    for kind in TABLES:
        print("  %-10s %s" % (kind, " ".join(str(I.dispatch_max(kind, c))
                                              for c in range(1 << I.CNT_W))))
    print("  usb_send   %d    other %d" % (I.dispatch_max("usb_send"), I.dispatch_max("other")))
    # must-fires: each perturbation of the fresh text must read red
    mf = (("a perturbed table entry", fresh.replace("pg_max_usb_rx = 10;", "pg_max_usb_rx = 64;", 1)),
          ("a missing kind", fresh.replace("pg_max_st_shiftin", "pg_max_st_shiftinX")))
    for what, text in mf:
        red = text != fresh and bool(problems(text, fresh))
        print("  must-fire: %-28s %s" % (what, "red  ok" if red else "*** STAYED GREEN"))
        if not red:
            probs.append("must-fire stayed green: " + what)
    for p in probs:
        print("  *** " + p)
    print("  GATE progress-bounds: %s" % ("PASSED" if not probs else "FAILED"))
    return 1 if probs else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
