"""GATE layers-rc -- src/config.json's wire RC is the generated one, not a typed one.

    python model/gate_layers_rc.py          (token: GATE layers-rc: PASSED)

The flow's per-layer RC (LAYERS_RC) and its averaging layers are GENERATED by
model/gen_layers_rc.py from a routed run's RCX extraction, cross-checked on a second
netlist, and recorded in model/layers_rc_of_record.json (Wilson 11-13). This gate
re-derives the config keys from the record and requires src/config.json to carry
exactly those, and the record's own check to be within its tolerance.
Before the configuration of record lands there is no record: the gate reads STALE
with its owner (model/stale_records.py), never a silent pass.
MUST-FIRES: a hand-edited capacitance, TopMetal1 back in the signal averaging, and a
record whose check run disagrees by more than the tolerance -- each red.
"""
from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_layers_rc as G  # noqa: E402

KEYS = ("LAYERS_RC", "SIGNAL_WIRE_RC_LAYERS", "CLOCK_WIRE_RC_LAYERS")


def judge(cfg, rec):
    """[problem] for a config dict against a layers-rc record"""
    out = []
    want = G.config_keys(rec)
    for k in KEYS:
        if cfg.get(k) != want[k]:
            out.append("src/config.json %s = %s, the record generates %s" % (k, json.dumps(cfg.get(k)), json.dumps(want[k])))
    out += ["the record's check: " + p for p in G.agreement(rec["source"], rec["check"], rec["tol"])]
    return out


def must_fires(cfg, rec):
    rows = []
    c1 = json.loads(json.dumps(cfg))
    c1["LAYERS_RC"]["*"]["Metal3"]["cap"] *= 1.05
    rows.append(("a hand-edited Metal3 capacitance (+5 %)", bool(judge(c1, rec))))
    c2 = dict(cfg, SIGNAL_WIRE_RC_LAYERS=list(G.LAYERS) + ["TopMetal1"])
    rows.append(("TopMetal1 back in the signal averaging", bool(judge(c2, rec))))
    r3 = json.loads(json.dumps(rec))
    r3["check"]["layers"]["Metal4"]["cap"] *= 1 + 2 * rec["tol"]
    rows.append(("a record whose check run disagrees", bool(judge(cfg, r3))))
    return rows


def main() -> int:
    print("GATE layers-rc -- the flow's wire RC is the generated one")
    if not os.path.exists(G.RECORD):
        import stale_records
        tag = stale_records.DECLARED.get("model/gate_layers_rc.py")
        if tag:
            print(stale_records.token("layers-rc", tag))
            return 0
        print("  *** no record (model/layers_rc_of_record.json) and no STALE declaration")
        print("  GATE layers-rc: FAILED")
        return 1
    rec = json.load(open(G.RECORD, encoding="utf-8"))
    cfg = json.load(open(G.CONFIG, encoding="utf-8"))
    probs = judge(cfg, rec)
    for label, red in must_fires(cfg, rec):
        print("  must-fire: %-42s %s" % (label, "red  ok" if red else "*** STAYED GREEN"))
        if not red:
            probs.append("must-fire stayed green: " + label)
    for p in probs:
        print("  *** " + p)
    print("  GATE layers-rc: %s" % ("PASSED" if not probs else "FAILED"))
    return 1 if probs else 0


if __name__ == "__main__":
    sys.exit(main())
